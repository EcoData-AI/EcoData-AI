"""Course outlines: what a valid one looks like, and generating one.

An outline is `{"modules": [{"title": str, "topics": [str, ...]}, ...]}`.
Topics are the unit of progress — `LearningProgress` rows are keyed by topic
title — so titles must be unique within a course. Every outline is validated
here before it is stored, whichever way it arrived: generated by the Study
screen's "New course" (`generate_outline`), or proposed by the chat model
through the `start_course` tool.
"""

from __future__ import annotations

import json
import re
from typing import Any

from gaia.llm.base import ChatMessage, LLMProvider, ProviderError

LEVELS = ("beginner", "intermediate", "advanced")
MAX_MODULES = 12
MAX_TOPICS_PER_MODULE = 12
MAX_TITLE_LENGTH = 200
GENERATION_MAX_TOKENS = 2000


class CurriculumError(ValueError):
    """An outline that cannot be stored. The message is shown to the user (or
    handed back to the model) as-is, so it says what to fix."""


def normalise_topic(title: str) -> str:
    return " ".join(title.split()).casefold()


def _clean_title(value: Any, what: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise CurriculumError(f"every {what} needs a non-empty title")
    title = " ".join(value.split())
    if len(title) > MAX_TITLE_LENGTH:
        raise CurriculumError(f"{what} title is too long (max {MAX_TITLE_LENGTH}): {title[:40]}…")
    return title


def validate_outline(raw: Any) -> dict[str, Any]:
    """Return a cleaned copy of `raw`, or raise `CurriculumError`."""
    if not isinstance(raw, dict) or not isinstance(raw.get("modules"), list):
        raise CurriculumError("an outline must be an object with a 'modules' list")
    modules_in = raw["modules"]
    if not 1 <= len(modules_in) <= MAX_MODULES:
        raise CurriculumError(f"a course needs between 1 and {MAX_MODULES} modules")

    seen: set[str] = set()
    modules: list[dict[str, Any]] = []
    for module in modules_in:
        if not isinstance(module, dict):
            raise CurriculumError("each module must be an object with 'title' and 'topics'")
        title = _clean_title(module.get("title"), "module")
        topics_in = module.get("topics")
        if not isinstance(topics_in, list) or not 1 <= len(topics_in) <= MAX_TOPICS_PER_MODULE:
            raise CurriculumError(
                f"module '{title}' needs between 1 and {MAX_TOPICS_PER_MODULE} topics"
            )
        topics: list[str] = []
        for topic in topics_in:
            topic_title = _clean_title(topic, "topic")
            key = normalise_topic(topic_title)
            if key in seen:
                raise CurriculumError(f"topic titles must be unique; '{topic_title}' repeats")
            seen.add(key)
            topics.append(topic_title)
        modules.append({"title": title, "topics": topics})
    return {"modules": modules}


def all_topics(outline: dict[str, Any] | None) -> list[str]:
    if not outline:
        return []
    return [topic for module in outline.get("modules", []) for topic in module.get("topics", [])]


def find_topic(outline: dict[str, Any] | None, title: str) -> str | None:
    """The outline's own spelling of `title`, matched ignoring case and spacing."""
    wanted = normalise_topic(title)
    return next((t for t in all_topics(outline) if normalise_topic(t) == wanted), None)


def _generation_prompt(subject: str, goal: str | None, level: str | None) -> str:
    lines = [
        f"Design a self-study course on: {subject}",
    ]
    if goal:
        lines.append(f"The learner's goal: {goal}")
    lines.append(
        f"The learner's level: {level}"
        if level
        else "The learner's level is not known yet; start from fundamentals, the course will "
        "adapt after a short diagnostic."
    )
    lines.append(
        "\nOrganise it into 3 to 8 modules, in teaching order, each with 2 to 6 topics. A topic "
        "is one concept small enough to teach and check in a single sitting. Topic titles must "
        "be unique across the whole course.\n"
        "Respond with JSON only, no prose and no code fence, in exactly this shape: "
        '{"modules": [{"title": "...", "topics": ["...", "..."]}]}'
    )
    return "\n".join(lines)


def parse_outline_json(text: str) -> Any:
    """Pull a JSON object out of a model reply, tolerating a code fence or a
    sentence of preamble — models add both despite being told not to."""
    fenced = re.search(r"```(?:json)?\s*(.*?)```", text, re.DOTALL)
    candidate = fenced.group(1) if fenced else text
    start, end = candidate.find("{"), candidate.rfind("}")
    if start == -1 or end <= start:
        raise CurriculumError("the model did not return a course outline")
    try:
        return json.loads(candidate[start : end + 1])
    except json.JSONDecodeError as exc:
        raise CurriculumError("the model's course outline was not valid JSON") from exc


async def generate_outline(
    provider: LLMProvider,
    model_id: str,
    *,
    subject: str,
    goal: str | None = None,
    level: str | None = None,
) -> dict[str, Any]:
    """Ask the configured model for an outline. Raises `ProviderError` if the
    provider fails, `CurriculumError` if what came back is not a usable outline."""
    chunks: list[str] = []
    async for event in provider.stream_chat(
        [ChatMessage(role="user", content=_generation_prompt(subject, goal, level))],
        model=model_id,
        temperature=0.4,
        max_tokens=GENERATION_MAX_TOKENS,
        tools=None,
    ):
        if event.type == "text":
            chunks.append(event.text)
        elif event.type == "error":
            raise ProviderError((event.error or {}).get("message", "course generation failed"))
    return validate_outline(parse_outline_json("".join(chunks)))
